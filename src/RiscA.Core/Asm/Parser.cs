using RiscA.Core.ISA;
using System;
using System.Collections;
using System.Collections.Generic;
using System.Data;
using System.Runtime.InteropServices;
using System.Text;
using System.Text.RegularExpressions;

namespace RiscA.Core.Asm
{

    public class ParsedInstruction()
    {
        public List<Instruction> Instructions { get; init; } = [];
        public string? Label { get; set; }
        //late-bound label references of this line (doc/assembler-architecture.md, 6.2);
        //replaces the single RefLabel of the pre-A1 assembler: one line can carry several fixups
        public List<Fixup> Fixups { get; init; } = [];
        //labels of expanded 'la'/'j'/'call' whose constant pool slot the assembler has to create (6.3)
        public List<string> PoolRequests { get; init; } = [];
        //set on the line of a '.func': marks the boundary of a pool region
        public bool IsFunc { get; set; }
        //inline mini pool of a relaxed 'la': halfword index of its LDI inside this line (doc 6.4),
        //-1 when the line has no inline pool; the alignment NOP and the dw immediates are kept
        //up to date by the relaxation loop
        public int InlineSlot { get; set; } = -1;
        public bool IsDW { get; set; }
        public bool IsDB { get; set; }
        //the line is a constant pool slot generated by the assembler (doc 6.3)
        public bool IsPool { get; set; }
    }

    public class Parser
    {
        static List<(List<TK[]>, Func<ParsedInstruction, List<TK[]>, List<Token>, int, List<Token>?>)> rules =
            [
                //Expressions
                ([ [TK.MINUS], [TK.NUMBER] ], ExpNegative),
                ([ [TK.LPAREN], [TK.NUMBER], [TK.RPAREN] ], ExpParen),
                ([ [TK.NUMBER], [TK.ASTER, TK.SLASH], [TK.NUMBER] ], ExpMath),
                ([ [TK.NUMBER], [TK.MINUS], [TK.NUMBER] ], ExpMath),
                ([ [TK.NUMBER], [TK.PLUS], [TK.NUMBER] ], ExpMath),
                ([ [TK.LITERAL], [TK.COLON] ], ExpLabel),

                //Instructions
                ([ [TK.MOV,TK.ADD,TK.SUB,TK.AND,TK.OR,TK.XOR,TK.NOT,TK.MUL,TK.SLT,TK.SLTU], [TK.REG], [TK.COMMA], [TK.REG], [TK.EOL] ], ParseAlu),
                ([ [TK.SHL, TK.SHR, TK.ADD, TK.SUB], [TK.REG], [TK.COMMA], [TK.NUMBER], [TK.EOL] ], ParseAluImm),
                ([ [TK.MOVI, TK.MOVL], [TK.REG], [TK.COMMA], [TK.NUMBER], [TK.EOL] ], ParseRegImm),

                //pseudo ops expanded right here into real instructions (doc/assembler-architecture.md, 6.1):
                //li/la with a number build the MOVI/MOVL chain, la with a label leaves a PoolRef fixup,
                //j leaves a Jr fixup - pass B of the assembler binds them and relaxes when an offset does not fit
                ([ [TK.LI], [TK.REG], [TK.COMMA], [TK.NUMBER], [TK.EOL] ], ParseLI),
                ([ [TK.LA], [TK.REG], [TK.COMMA], [TK.NUMBER], [TK.EOL] ], ParseLI),
                ([ [TK.LA], [TK.REG], [TK.COMMA], [TK.LITERAL], [TK.EOL] ], ParseLA),
                ([ [TK.J], [TK.NUMBER, TK.LITERAL], [TK.EOL] ], ParseJ),
                ([ [TK.J], [TK.NUMBER, TK.LITERAL], [TK.COMMA], [TK.REG], [TK.EOL] ], ParseJ),
                ([ [TK.LDB, TK.LDW], [TK.REG], [TK.COMMA], [TK.LSBRACKET], [TK.REG], [TK.PLUS], [TK.NUMBER], [TK.RSBRACKET], [TK.EOL] ], ParseLD),
                ([ [TK.STB, TK.STW], [TK.LSBRACKET], [TK.REG], [TK.PLUS], [TK.NUMBER], [TK.RSBRACKET], [TK.COMMA], [TK.REG], [TK.EOL] ], ParseST),
                ([ [TK.BEQZ, TK.BNEZ], [TK.REG], [TK.COMMA], [TK.NUMBER, TK.LITERAL], [TK.EOL] ], ParseBranch),
                ([ [TK.LDI], [TK.REG], [TK.COMMA], [TK.LSBRACKET], [TK.NUMBER,TK.LITERAL], [TK.RSBRACKET], [TK.EOL] ], ParseLDI),
                ([ [TK.CALL, TK.JR], [TK.NUMBER, TK.LITERAL], [TK.EOL] ], ParseCallJr),
                ([ [TK.CALL, TK.JMP, TK.INT], [TK.REG], [TK.EOL] ], ParseCallJmpInt),
                ([ [TK.RET, TK.RETI], [TK.EOL] ], ParseRet),
                ([ [TK.MOV], [TK.REG], [TK.COMMA], [TK.EPC], [TK.EOL] ], ParseEPC),
                ([ [TK.MOV], [TK.EPC], [TK.COMMA], [TK.REG], [TK.EOL] ], ParseEPC),
                ([ [TK.NOP], [TK.EOL] ], ParseNop),

                ([ [TK.DB], [TK.STRING, TK.NUMBER] ], ParseDB),
                ([ [TK.DW], [TK.NUMBER, TK.LITERAL], [TK.EOL] ], ParseDW),

                //Skip rules
                ([ [TK.EOL] ], Skip), //empty line
            ];

        public static ParsedInstruction ParseLine(string line)
        {
            return ParseLine(line, null);
        }

        public static ParsedInstruction ParseLine(string line, IReadOnlyDictionary<string, int>? constants)
        {
            List<Token> tokens = Tokenizer.tokenizeLine(line);
            SubstituteConstants(tokens, constants);
            ParsedInstruction parsedInstruction = new ParsedInstruction();
            while (ProcessToken(tokens, parsedInstruction))
                ;

            if (tokens.Count > 0) //TODO: find most matched rule to clarify error
            {
                throw new Exception($"Syntax error: {string.Join(",", tokens.ConvertAll(x => $"{x.TokenType}({x.TokenString})"))}");
            }
            return parsedInstruction;
        }

        //turns '.equ' constants into number tokens before the rules run, so a constant can be
        //used anywhere a number is expected: immediates, [r+off] offsets, db/dw values
        static void SubstituteConstants(List<Token> tokens, IReadOnlyDictionary<string, int>? constants)
        {
            if (constants is null || constants.Count == 0)
                return;
            for (int i = 0; i < tokens.Count; i++)
            {
                if (tokens[i].TokenType != TK.LITERAL)
                    continue;
                if (!constants.TryGetValue(tokens[i].TokenString, out int value))
                    continue;
                if (i + 1 < tokens.Count && tokens[i + 1].TokenType == TK.COLON)
                    throw new Exception($"'{tokens[i].TokenString}' is a .equ constant, it cannot be used as a label");
                tokens[i] = new Token(TK.NUMBER, tokens[i].TokenString, tokens[i].TokenPos, value);
            }
        }

        private static bool ProcessToken(List<Token> stack, ParsedInstruction pi)
        {
            foreach(var rule in rules)
            {
                var (pattern, handler) = rule;
                if (pattern.Count > stack.Count)
                    continue;
                for (int startPos = 0; startPos <= stack.Count - pattern.Count; startPos++)
                {
                    bool ruleMatch = true;
                    for (int i = 0; i < pattern.Count; i++)
                    {
                        if (Array.IndexOf(pattern[i], stack[startPos + i].TokenType) < 0)
                        {
                            ruleMatch = false;
                            break;
                        }
                    }
                    if (ruleMatch)
                    {
                        var matchedTokens = stack.GetRange(startPos, pattern.Count);
                        var result = handler(pi, pattern, stack, startPos);
                        if(result == null)
                            continue;
                        if(Verbose.ParserMatches)
                            Console.WriteLine($"P: {handler.Method.Name} {string.Join(",", matchedTokens.ConvertAll(x => $"{x.TokenType}({x.TokenString})"))}");
                        stack = result;
                        return true;
                    }
                }
            }
            return false;
        }

        static List<Token>? Skip(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            tokens.RemoveRange(pos, rule.Count);
            return tokens;
        }

        static List<Token>? ParseAlu(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.ALU_REG_REG)
                .withFunc4(rule[0].IndexOf(tokens[pos].TokenType))
                .withRd(tokens[pos + 1].intValue)
                .withRs(tokens[pos + 3].intValue);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 5);
            return tokens;
        }

        static List<Token>? ParseAluImm(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.ALU_REG_IMM)
                .withFunc2(rule[0].IndexOf(tokens[pos].TokenType))
                .withRd(tokens[pos + 1].intValue)
                .withImm7(tokens[pos + 3].intValue);
            i.CheckImmLimits(tokens[pos + 3].intValue);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 5);
            return tokens;
        }

        static List<Token>? ParseRegImm(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.REG_IMM)
                .withFunc1(rule[0].IndexOf(tokens[pos].TokenType))
                .withRd(tokens[pos + 1].intValue)
                .withImm8(tokens[pos + 3].intValue);
            i.CheckImmLimits(tokens[pos + 3].intValue);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 5);
            return tokens;
        }
        static List<Token>? ParseLD(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.ST_LD)
                .withFunc21(0)
                .withFunc22(rule[0].IndexOf(tokens[pos].TokenType))
                .withRd(tokens[pos + 1].intValue)
                .withRs(tokens[pos + 4].intValue)
                .withImm3(tokens[pos + 6].intValue);
            i.CheckImmLimits(tokens[pos + 6].intValue);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 9);
            return tokens;
        }

        static List<Token>? ParseST(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.ST_LD)
                .withFunc21(1)
                .withFunc22(rule[0].IndexOf(tokens[pos].TokenType))
                .withRd(tokens[pos + 7].intValue)
                .withRs(tokens[pos + 2].intValue)
                .withImm3(tokens[pos + 4].intValue);
            i.CheckImmLimits(tokens[pos + 4].intValue);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 9);
            return tokens;
        }

        static List<Token>? ParseBranch(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var imm8 = tokens[pos + 3].TokenType == TK.NUMBER ? tokens[pos + 3].intValue : 0;
            var i = new Instruction(0)
                .withOpCode(OpCode.BRANCH)
                .withFunc1(rule[0].IndexOf(tokens[pos].TokenType))
                .withRd(tokens[pos + 1].intValue)
                .withImm8(imm8);

            if (tokens[pos + 3].TokenType == TK.LITERAL)
                parsedInstruction.Fixups.Add(new Fixup(parsedInstruction.Instructions.Count, tokens[pos + 3].TokenString, FixupKind.Branch));
            else
                i.CheckImmLimits(imm8);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 5);
            return tokens;
        }

        //li Rd, value and la Rd, <number>: the exact MOVI/MOVL byte chain of the constant
        //beginning with its highest non zero byte (doc/assembler-architecture.md, 6.1);
        //no peephole shrinking here - that stays a back-end optimization of the compiler
        static List<Token>? ParseLI(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            int rd = tokens[pos + 1].intValue;
            uint value = unchecked((uint)tokens[pos + 3].intValue);
            int first = 0;
            while (first < 3 && ((value >> (24 - first * 8)) & 0xFF) == 0)
                first++;
            for (int b = first; b < 4; b++)
            {
                int imm8 = (int)((value >> (24 - b * 8)) & 0xFF);
                var i = new Instruction(0)
                    .withOpCode(OpCode.REG_IMM)
                    .withFunc1(b == first ? (int)RegImmFunc.MOVI : (int)RegImmFunc.MOVL)
                    .withRd(rd)
                    .withImm8(imm8);
                parsedInstruction.Instructions.Add(i);
            }
            tokens.RemoveRange(pos, 5);
            return tokens;
        }

        //la Rd, label: an LDI placeholder bound to the label's constant pool slot by the assembler;
        //when the slot turns out unreachable (more than +-256 instructions) pass B rewrites the line
        //into an inline mini pool on the spot (doc/assembler-architecture.md, 6.3 - 6.4)
        static List<Token>? ParseLA(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.LDI)
                .withRd(tokens[pos + 1].intValue)
                .withImm9(0);
            parsedInstruction.Instructions.Add(i);
            parsedInstruction.Fixups.Add(new Fixup(parsedInstruction.Instructions.Count - 1, tokens[pos + 3].TokenString, FixupKind.PoolRef));
            parsedInstruction.PoolRequests.Add(tokens[pos + 3].TokenString);
            tokens.RemoveRange(pos, 5);
            return tokens;
        }

        //j label[, rN]: a JR placeholder; if the label turns out farther than the +-1024 instructions
        //of JR, pass B rewrites the line to LDI rN from the pool plus JMP rN (doc 6.1, 6.4).
        //The absolute address then always travels in a dw entry, never in an immediate.
        static List<Token>? ParseJ(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var target = tokens[pos + 1];
            var i = new Instruction(0)
                .withOpCode(OpCode.CALL_JMP_RET)
                .withFunc2((int)CallJmpRetFunc.JR);
            if (target.TokenType == TK.NUMBER)
            {
                //a jump to an absolute number uses the same split encoding as 'call number'
                int refaddr = target.intValue;
                i = i.withRd(refaddr & 0b0000_1111).withImm7((refaddr >> 4) & 0b0111_1111);
                i.CheckImmLimits(refaddr);
                parsedInstruction.Instructions.Add(i);
            }
            else
            {
                var fx = new Fixup(parsedInstruction.Instructions.Count, target.TokenString, FixupKind.Jr);
                if (rule.Count == 5) //j label, rN - the scratch register of the LDI+JMP fallback
                    fx.Reg = tokens[pos + 3].intValue;
                parsedInstruction.Instructions.Add(i);
                parsedInstruction.Fixups.Add(fx);
            }
            tokens.RemoveRange(pos, rule.Count);
            return tokens;
        }

        //[TK.LDI], [TK.REG], [TK.COMMA], [TK.LSBRACKET], [TK.NUMBER,TK.LITERAL], [TK.RSBRACKET], [TK.EOL]
        static List<Token>? ParseLDI(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            int imm9 = tokens[pos + 4].TokenType == TK.NUMBER ? tokens[pos + 4].intValue : 0;
            var i = new Instruction(0)
                .withOpCode(OpCode.LDI)
                .withRd(tokens[pos + 1].intValue)
                .withImm9(imm9);
            if (tokens[pos + 4].TokenType == TK.LITERAL)
                //a hand written ldi loads the contents at the label, not the address of a pool slot:
                //it has no Target fixup and cannot be relaxed, so an unreachable label is an error
                parsedInstruction.Fixups.Add(new Fixup(parsedInstruction.Instructions.Count, tokens[pos + 4].TokenString, FixupKind.PoolRef));
            else
                i.CheckImmLimits(imm9);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 7);
            return tokens;
        }

        //[TK.CALL, TK.JR], [TK.NUMBER, TK.LITERAL], [TK.EOL]
        static List<Token>? ParseCallJr(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            int refaddr = tokens[pos + 1].TokenType == TK.NUMBER ? tokens[pos + 1].intValue : 0;
            int rd = refaddr & 0b0000_1111;
            int imm7 = (refaddr >> 4) & 0b0111_1111;

            var i = new Instruction(0)
                .withOpCode(OpCode.CALL_JMP_RET)
                .withFunc2(tokens[pos].TokenType == TK.JR ? 3 : 0)
                .withRd(rd)
                .withImm7(imm7);
            if (tokens[pos + 1].TokenType == TK.NUMBER)
                i.CheckImmLimits(refaddr);
            else
                parsedInstruction.Fixups.Add(new Fixup(parsedInstruction.Instructions.Count, tokens[pos + 1].TokenString,
                    tokens[pos].TokenType == TK.JR ? FixupKind.Jr : FixupKind.Call));
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 3);
            return tokens;
        }

        //[TK.CALL, TK.JMP, TK.INT], [TK.REG], [TK.EOL]
        static List<Token>? ParseCallJmpInt(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var func2 = (tokens[pos].TokenType) switch
            {
                TK.CALL => 1,
                TK.JMP => 2,
                TK.INT => 0,
                _ => 0,
            };
            var i = new Instruction(0)
                .withOpCode(tokens[pos].TokenType == TK.INT ? OpCode.INT_RETI : OpCode.CALL_JMP_RET)
                .withFunc2(func2)
                .withRd(tokens[pos + 1].intValue);
            ;
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 3);
            return tokens;
        }

        //[TK.RET, TK.RETI], [TK.EOL]
        static List<Token>? ParseRet(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(tokens[pos].TokenType == TK.RETI ? OpCode.INT_RETI : OpCode.CALL_JMP_RET)
                .withFunc2(tokens[pos].TokenType == TK.RETI ? 1 : 2)
                .withRd(tokens[pos].TokenType == TK.RETI ? 0 : 14); //R14 link register
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 2);
            return tokens;
        }

        //[TK.MOV], [TK.REG], [TK.COMMA], [TK.EPC], [TK.EOL]
        //[TK.MOV], [TK.EPC], [TK.COMMA], [TK.REG], [TK.EOL]
        static List<Token>? ParseEPC(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.INT_RETI)
                .withFunc2(tokens[pos + 1].TokenType == TK.REG ? 2 : 3)
                .withRd(tokens[pos+1].TokenType == TK.REG ? tokens[pos + 1].intValue : tokens[pos + 3].intValue); //R14 link register
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 5);
            return tokens;
        }

        //[TK.NOP], [TK.EOL]
        static List<Token>? ParseNop(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            var i = new Instruction(0)
                .withOpCode(OpCode.ALU_REG_REG)
                .withFunc4((int)ALUFunc.MOV)
                .withRd(0)
                .withRs(0);
            parsedInstruction.Instructions.Add(i);
            tokens.RemoveRange(pos, 2);
            return tokens;
        }

        static List<Token>? ExpMath(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            int a = tokens[pos + 0].intValue;
            int b = tokens[pos + 2].intValue;
            int c = tokens[pos + 1].TokenType switch
            {
                TK.PLUS => a + b,
                TK.MINUS => a - b,
                TK.ASTER => a * b,
                TK.SLASH => a / b,
                _ => throw new Exception($"Unexpected math operation '{tokens[pos + 1].TokenString}' in '{tokens[pos].TokenString} {tokens[pos + 1].TokenString} {tokens[pos + 2].TokenString}'")
            };
            tokens.RemoveRange(pos, 3);
            tokens.Insert(pos, new Token(TK.NUMBER, c.ToString(), pos, c));
            return tokens;
        }

        static List<Token>? ExpParen(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            Token number = tokens[pos + 1];
            tokens.RemoveRange(pos, 3);
            tokens.Insert(pos, number);
            return tokens;
        }

        static List<Token>? ExpNegative(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            if (pos > 0 && tokens[pos - 1].TokenType is TK.NUMBER or TK.RPAREN)
                return null;
            Token number = tokens[pos + 1];
            number.intValue = 0 - number.intValue;
            number.TokenString = number.intValue.ToString();
            tokens.RemoveRange(pos, 2);
            tokens.Insert(pos, number);
            return tokens;
        }

        //[TK.LITERAL], [TK.COLON]
        static List<Token>? ExpLabel(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            parsedInstruction.Label = tokens[pos].TokenString;
            tokens.RemoveRange(pos, 2);
            return tokens;
        }

        static List<Token>? ParseDB(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            parsedInstruction.IsDB = true;
            var bytes = new List<byte>();
            int i = pos + 1;
            while (i < tokens.Count && tokens[i].TokenType != TK.EOL)
            {
                if (tokens[i].TokenType == TK.COMMA)
                {
                    i++;
                    continue;
                }
                if (tokens[i].TokenType == TK.STRING)
                {
                    foreach (char c in tokens[i].strValue!)
                        bytes.Add((byte)c);
                    i++;
                    continue;
                }
                if (tokens[i].TokenType == TK.NUMBER)
                {
                    int val = tokens[i].intValue;
                    if (val < -128 || val > 255)
                        throw new Exception($"Syntax error {tokens[i].TokenPos}: value {val} out of range -128..255 for db");
                    bytes.Add((byte)val);
                    i++;
                    continue;
                }
                throw new Exception($"Syntax error {tokens[i].TokenPos}: unexpected '{tokens[i].TokenString}' in db directive");
            }

            for (int j = 0; j < bytes.Count; j += 2)
            {
                ushort raw = bytes[j];
                if (j + 1 < bytes.Count)
                    raw |= (ushort)(bytes[j + 1] << 8);
                parsedInstruction.Instructions.Add(new Instruction(raw));
            }

            tokens.RemoveRange(pos, i - pos + 1);
            return tokens;
        }

        static List<Token>? ParseDW(ParsedInstruction parsedInstruction, List<TK[]> rule, List<Token> tokens, int pos)
        {
            parsedInstruction.IsDW = true;
            if (tokens[pos + 1].TokenType == TK.NUMBER)
            {
                int val = tokens[pos + 1].intValue;
                ushort low = unchecked((ushort)(val & 0xFFFF));
                ushort high = unchecked((ushort)((val >> 16) & 0xFFFF));
                parsedInstruction.Instructions.Add(new Instruction(low));
                parsedInstruction.Instructions.Add(new Instruction(high));
            }
            else
            {
                //dw label: the absolute address of the label is written into the pair of raw
                //halfwords by pass B (DataAddr fixup), so it never travels inside an immediate
                parsedInstruction.Fixups.Add(new Fixup(parsedInstruction.Instructions.Count, tokens[pos + 1].TokenString, FixupKind.DataAddr));
                parsedInstruction.Instructions.Add(new Instruction(0));
                parsedInstruction.Instructions.Add(new Instruction(0));
            }
            tokens.RemoveRange(pos, 3);
            return tokens;
        }
    }
